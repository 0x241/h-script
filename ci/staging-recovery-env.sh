#!/bin/sh
# Append to the private staging .env; never invoke with shell tracing enabled.
set -eu
set +x
emit() {
    # Single-quoted dotenv values are literal in Compose. Reject line/quote
    # injection rather than letting configuration create another env entry.
    case "$2" in *"'"*|*'
'*|*"$(printf '\r')"*) echo "Invalid recovery environment value: $1" >&2; exit 1 ;; esac
    printf "%s='%s'\n" "$1" "$2"
}
emit RECOVERY_ENABLED "${RECOVERY_ENABLED:-0}"
emit RECOVERY_BACKUP_INTERVAL_SECONDS "${RECOVERY_BACKUP_INTERVAL_SECONDS:-3600}"
emit RECOVERY_SECRETS_PATH "${RECOVERY_SECRETS_PATH:-./docker/recovery/secrets}"
emit RECOVERY_ROW_BOUNDS_FILE "${RECOVERY_ROW_BOUNDS_FILE:-/run/secrets/hscript-recovery/row-bounds.json}"
emit RECOVERY_DRILL_DB_HOST "${RECOVERY_DRILL_DB_HOST:-database:3306}"
emit RECOVERY_DRILL_DB_ADMIN_USER "${RECOVERY_DRILL_DB_ADMIN_USER:-root}"
emit RECOVERY_DRILL_DB_ADMIN_PASSWORD "${RECOVERY_DRILL_DB_ADMIN_PASSWORD:-}"
emit RECOVERY_DRILL_DB_ADMIN_PASSWORD_FILE "${RECOVERY_DRILL_DB_ADMIN_PASSWORD_FILE:-}"
emit RECOVERY_DRILL_DB_PREFIX "${RECOVERY_DRILL_DB_PREFIX:-hscript_drill}"
emit RECOVERY_RUNTIME_PATHS "${RECOVERY_RUNTIME_PATHS:-upload,themes}"
emit RECOVERY_INCLUDE_PROTECTED_CONFIG "${RECOVERY_INCLUDE_PROTECTED_CONFIG:-0}"
emit RECOVERY_RUNTIME_MAX_FILES "${RECOVERY_RUNTIME_MAX_FILES:-100000}"
emit RECOVERY_RUNTIME_MAX_BYTES "${RECOVERY_RUNTIME_MAX_BYTES:-10737418240}"
emit RECOVERY_ALERT_COMMAND "${RECOVERY_ALERT_COMMAND:-}"
emit RECOVERY_CMS_RPO_SECONDS "${RECOVERY_CMS_RPO_SECONDS:-86400}"
emit RECOVERY_CMS_RTO_SECONDS "${RECOVERY_CMS_RTO_SECONDS:-14400}"
emit RECOVERY_COLLECTOR_RPO_SECONDS "${RECOVERY_COLLECTOR_RPO_SECONDS:-21600}"
emit RECOVERY_COLLECTOR_RTO_SECONDS "${RECOVERY_COLLECTOR_RTO_SECONDS:-7200}"
emit RECOVERY_SERVICE_TOKENS_RPO_SECONDS "${RECOVERY_SERVICE_TOKENS_RPO_SECONDS:-21600}"
emit RECOVERY_SERVICE_TOKENS_RTO_SECONDS "${RECOVERY_SERVICE_TOKENS_RTO_SECONDS:-7200}"
emit RECOVERY_DRILL_MAX_AGE_SECONDS "${RECOVERY_DRILL_MAX_AGE_SECONDS:-604800}"
